"""Параметры мейкер-исполнения (лимитные заявки).

Мейкер ставит лимит у цены и платит сниженную комиссию (или получает ребейт),
НО заявка исполняется только если рынок дошёл до лимита. Если цена сразу
ушла в нашу сторону — заявка не исполнилась, вход пропущен.

Это adverse selection — главная цена мейкера: пропускаются именно те входы,
где движение сразу пошло в плюс. Без моделирования этого мейкер выглядел бы
бесплатным улучшением, что неверно.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class MakerParams:
    fee: float = -0.0001     # мейкер-комиссия на сторону (отрицательная = ребейт)
    offset: float = 0.0005   # насколько лимит «лучше» рынка (доля цены)
    fill_window: int = 5     # сколько баров ждём исполнения, иначе отмена

    def describe(self) -> str:
        return (f"maker[fee={self.fee:+.4%},off={self.offset:.2%},"
                f"win={self.fill_window}]")
